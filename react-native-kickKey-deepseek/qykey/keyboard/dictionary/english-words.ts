export async function getEnglishTrie(): Promise<Trie> {
  if (_trie) return _trie;
  _trie = new Trie();
  const filtered = (englishWords as string[]).filter((w) => w.length >= 2);

  for (const word of filtered) {
    const lower = word.toLowerCase();
    // Common words get frequency 1000, others get 1
    _trie.insert(lower, COMMON_WORDS.has(lower) ? 1000 : 1);
  }

  return _trie;
}
